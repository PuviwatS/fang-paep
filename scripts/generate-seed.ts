/**
 * Builds the SQL that loads the song catalogue and the daily puzzles into Supabase.
 *
 *   npx tsx scripts/generate-seed.ts [days]
 *
 * Writes:
 *   supabase/seed/01_catalog.sql        artists + songs from src/data/*.json
 *   supabase/seed/02_daily_puzzles.sql  the answer for every day and category tab
 *
 * Puzzles use the same shuffle as the original browser-only demo (src/lib/daily.ts), so the
 * answers for days that were already played do not change. Re-running is safe: every insert
 * is "on conflict do nothing", so existing rows are kept.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CATEGORIES } from "../src/lib/constants";
import { getDailySong } from "../src/lib/daily";
import { ARTIST_ALIASES, SONGS } from "../src/lib/songs";

const days = Number(process.argv[2] ?? 730);
const outDir = join(__dirname, "..", "supabase", "seed");
mkdirSync(outDir, { recursive: true });

const sqlText = (value: string) => `'${value.replace(/'/g, "''")}'`;
const sqlArray = (values: string[]) => `array[${values.map(sqlText).join(", ")}]::text[]`;

// ---- Catalogue ---------------------------------------------------------------

const artistNames = [...new Set(SONGS.map((song) => song.artist))];
const artistRows = artistNames.map((name) => `  (${sqlText(name)}, ${sqlArray(ARTIST_ALIASES[name] ?? [])})`);
const songRows = SONGS.map(
  (song) =>
    `  (${song.id}, ${sqlText(song.title)}, ${sqlText(song.artist)}, ${sqlText(song.category)}, ${song.year ? Number(song.year) : "null"})`,
);

writeFileSync(
  join(outDir, "01_catalog.sql"),
  `-- Generated by scripts/generate-seed.ts from src/data/*.json. ${SONGS.length} songs, ${artistNames.length} artists.
insert into public.artists (name, aliases) values
${artistRows.join(",\n")}
on conflict (name) do update set aliases = excluded.aliases;

insert into public.songs (id, title, artist_id, category, year)
select v.id, v.title, a.id, v.category, v.year
from (values
${songRows.join(",\n")}
) as v (id, title, artist, category, year)
join public.artists a on a.name = v.artist
on conflict (id) do nothing;
`,
);

// ---- Daily puzzles -------------------------------------------------------------

// One statement per category: the array position is the day number.
const puzzleStatements = CATEGORIES.map(({ key }) => {
  const ids = Array.from({ length: days }, (_, i) => getDailySong(key, i + 1).id);
  return `insert into public.daily_puzzles (day, category, song_id)
select t.day, ${sqlText(key)}, t.song_id
from unnest(array[${ids.join(",")}]::bigint[]) with ordinality as t (song_id, day)
on conflict (day, category) do nothing;`;
});

writeFileSync(
  join(outDir, "02_daily_puzzles.sql"),
  `-- Generated by scripts/generate-seed.ts: days 1-${days} for every category tab.\n${puzzleStatements.join("\n\n")}\n`,
);

console.log(
  `Wrote ${artistNames.length} artists, ${SONGS.length} songs, ${days * CATEGORIES.length} puzzles to ${outDir}`,
);
